MATRA = "ािीुूृेैोौंःँॅ़"
CONS = "कखगघङचछजझञटठडढणतथदधनपफबभमयरलळवशषसहक़ख़ग़ज़ड़ढ़फ़"

def kd2uni(s: str) -> str:
    s = s.replace("±", "Zं").replace("Æ", "र्f").replace("Ç", "fa").replace("É", "र्fa")
    s = s.replace("Ê", "ीZ").replace("Ë", "ीZ")
    for a, b in zip(A1, A2):
        s = s.replace(a, b)
    # short-i matra is typed before the consonant: move it after the cluster
    s = re.sub(r"f((?:[%s]़?्)*[%s]़?)" % (CONS, CONS), r"\1ि", s)
    s = s.replace("f", "ि")
    # reph (Z) is typed after the syllable: move 'र्' to the front of it
    s = re.sub(r"((?:[%s]़?्)*[%s]़?[%s]*)Z" % (CONS, CONS, MATRA), r"र्\1", s)
    s = s.replace("Z", "र्")
    s = s.replace("अा", "आ").replace("ाे", "ो").replace("ाै", "ौ").replace("अो", "ओ").replace("अौ", "औ").replace("एे", "ऐ").replace("आॅ", "ऑ").replace("ाॅ", "ॉ").replace("ंे", "ें").replace("ंै", "ैं").replace("ंो", "ों").replace("ंी", "ीं").replace("ंु", "ुं").replace("ंू", "ूं")
    return s
